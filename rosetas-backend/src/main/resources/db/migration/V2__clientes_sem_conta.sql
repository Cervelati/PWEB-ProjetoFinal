-- Cliente deixa de ter conta: passa a ser apenas um cadastro de contato (nome, telefone, e-mail),
-- criado no checkout. O acompanhamento do pedido é feito por um código imprevisível no link.

create table clientes (
    id        bigint generated by default as identity primary key,
    nome      varchar(150) not null,
    telefone  varchar(20)  not null unique,   -- somente dígitos, com DDD
    email     varchar(255),
    criado_em timestamptz  not null default now()
);

alter table pedidos add column cliente_novo_id bigint references clientes (id);
alter table pedidos add column codigo_acompanhamento varchar(64);

-- Migra pedidos já existentes (ambiente de desenvolvimento): cada usuário-cliente vira um cliente.
do $$
declare
    r record;
    novo bigint;
    n int := 0;
begin
    for r in select distinct u.id, u.nome, u.email
             from usuarios u
             where u.id in (select cliente_id from pedidos)
    loop
        n := n + 1;
        insert into clientes (nome, telefone, email)
        values (r.nome, '0000000' || lpad(n::text, 4, '0'), r.email)
        returning id into novo;
        update pedidos set cliente_novo_id = novo where cliente_id = r.id;
    end loop;
end $$;

update pedidos
   set codigo_acompanhamento = replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', '')
 where codigo_acompanhamento is null;

alter table pedidos alter column cliente_novo_id set not null;
alter table pedidos alter column codigo_acompanhamento set not null;
alter table pedidos add constraint uq_pedidos_codigo unique (codigo_acompanhamento);

alter table pedidos drop column cliente_id;
alter table pedidos rename column cliente_novo_id to cliente_id;
create index ix_pedidos_cliente on pedidos (cliente_id);

-- Usuários agora são só a equipe.
delete from usuarios where perfil = 'CLIENTE';
