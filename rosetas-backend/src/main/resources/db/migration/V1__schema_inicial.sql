create table usuarios (
    id        varchar(128) primary key,           -- uid do Firebase
    nome      varchar(150) not null,
    email     varchar(255) not null unique,
    telefone  varchar(30),
    perfil    varchar(20)  not null,              -- CLIENTE, FUNCIONARIA, ADMIN, ROOT
    ativo     boolean      not null default true
);

create table fitas (
    id             bigint generated by default as identity primary key,
    nome           varchar(100) not null,
    hex            varchar(7)   not null,
    metros_estoque numeric(12,3) not null default 0 check (metros_estoque >= 0),
    foto           varchar(500),
    ativa          boolean      not null default true
);

create table modelos_roseta (
    id          bigint generated by default as identity primary key,
    nome        varchar(150) not null,
    descricao   varchar(1000),
    preco       numeric(12,2) not null check (preco >= 0),
    imagem_base varchar(500),
    ativo       boolean      not null default true
);

create table partes_modelo (
    id                bigint generated by default as identity primary key,
    modelo_id         bigint       not null references modelos_roseta (id),
    nome              varchar(100) not null,
    metros_consumidos numeric(10,3) not null check (metros_consumidos > 0)
);
create index ix_partes_modelo_modelo on partes_modelo (modelo_id);

create table pedidos (
    id          bigint generated by default as identity primary key,
    cliente_id  varchar(128)  not null references usuarios (id),
    status      varchar(30)   not null,
    valor_total numeric(12,2) not null check (valor_total >= 0),
    data        timestamptz   not null,
    observacoes varchar(1000)
);
create index ix_pedidos_cliente on pedidos (cliente_id);
create index ix_pedidos_status_data on pedidos (status, data);

create table itens_pedido (
    id                  bigint generated by default as identity primary key,
    pedido_id           bigint not null references pedidos (id),
    modelo_id           bigint not null references modelos_roseta (id),
    quantidade          int    not null check (quantidade > 0),
    texto_personalizado varchar(255)
);
create index ix_itens_pedido_pedido on itens_pedido (pedido_id);

create table personalizacoes_parte (
    id       bigint generated by default as identity primary key,
    item_id  bigint not null references itens_pedido (id),
    parte_id bigint not null references partes_modelo (id),
    fita_id  bigint not null references fitas (id)
);
create index ix_personalizacoes_item on personalizacoes_parte (item_id);

create table pagamentos (
    id                   bigint generated by default as identity primary key,
    pedido_id            bigint        not null references pedidos (id),
    valor                numeric(12,2) not null,
    metodo               varchar(20)   not null,   -- PIX
    status               varchar(20)   not null,   -- PENDENTE, APROVADO, FALHOU, EXPIRADO
    gateway_transacao_id varchar(100)  not null unique,
    pix_copia_cola       varchar(1000)
);
create index ix_pagamentos_pedido on pagamentos (pedido_id);
create index ix_pagamentos_status on pagamentos (status);

create table movimentos_estoque (
    id         bigint generated by default as identity primary key,
    fita_id    bigint        not null references fitas (id),
    quantidade numeric(12,3) not null check (quantidade > 0),
    tipo       varchar(20)   not null,             -- ENTRADA, RESERVA, BAIXA, ESTORNO
    pedido_id  bigint references pedidos (id),
    data       timestamptz   not null
);
create index ix_movimentos_fita on movimentos_estoque (fita_id);
create index ix_movimentos_pedido on movimentos_estoque (pedido_id);

create table historico_status (
    id              bigint generated by default as identity primary key,
    pedido_id       bigint       not null references pedidos (id),
    status_anterior varchar(30),
    status_novo     varchar(30)  not null,
    alterado_por    varchar(128) not null,
    data            timestamptz  not null
);
create index ix_historico_pedido on historico_status (pedido_id);

create table notificacoes (
    id           bigint generated by default as identity primary key,
    pedido_id    bigint       not null references pedidos (id),
    canal        varchar(20)  not null,            -- EMAIL, WHATSAPP
    template     varchar(80)  not null,
    status_envio varchar(20)  not null,            -- PENDENTE, ENVIADO, FALHOU
    data         timestamptz  not null
);
create index ix_notificacoes_status on notificacoes (status_envio);
