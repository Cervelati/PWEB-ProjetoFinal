-- Estoque de qualquer material (fitas, bottons, argolas, alfinetes...).
-- A tabela mantém o nome histórico "fitas" (colunas metros_estoque e ativa) para não quebrar as migrações antigas;
-- no código ela é a entidade Material.
alter table fitas add column tipo    varchar(20) not null default 'FITA';
alter table fitas add column unidade varchar(10) not null default 'METRO';
alter table fitas alter column hex drop not null;

insert into fitas (nome, hex, metros_estoque, tipo, unidade, ativa) values
    ('Botton',   null, 0, 'BOTTON',   'UNIDADE', true),
    ('Argola',   null, 0, 'ARGOLA',   'UNIDADE', true),
    ('Alfinete', null, 0, 'ALFINETE', 'UNIDADE', true);

-- Particularidades de cada roseta (lista de preços 2026)
alter table modelos_roseta
    add column referencia             varchar(40),
    add column categoria              varchar(40),
    add column formato                varchar(20),
    add column diametro_cm            numeric(5,1),
    add column voltas                 int,
    add column rabiola_qtd            int not null default 0,
    add column rabiola_comprimento_cm numeric(6,1),
    add column largura_fita_cm        numeric(4,1),
    add column preco_americano        numeric(12,2) check (preco_americano is null or preco_americano >= 0),
    add column preco_normal           numeric(12,2) check (preco_normal is null or preco_normal >= 0),
    add column gravacoes_inclusas     int not null default 0;
create unique index uq_modelos_referencia on modelos_roseta (referencia) where referencia is not null;

-- Corpo (voltas) x rabiola: cada parte é uma cor escolhida pelo cliente
alter table partes_modelo add column grupo varchar(20) not null default 'CORPO';

-- Materiais fixos consumidos por unidade de cada modelo (botton, argola, alfinete...)
create table componentes_modelo (
    id          bigint generated by default as identity primary key,
    modelo_id   bigint        not null references modelos_roseta (id),
    material_id bigint        not null references fitas (id),
    quantidade  numeric(10,3) not null check (quantidade > 0)
);
create index ix_componentes_modelo on componentes_modelo (modelo_id);

-- Escolhas do cliente no item
alter table itens_pedido
    add column franzido        varchar(10),
    add column gravacoes_extras int not null default 0,
    add column preco_unitario  numeric(12,2);
